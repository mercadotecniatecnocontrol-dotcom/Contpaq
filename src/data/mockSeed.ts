function makeUuid(seed: string): string {
  // Hash determinístico sin colisiones a formato oficial UUID SAT 8-4-4-4-12
  const hashPart = (input: string, salt: number): string => {
    let h = (2166136261 ^ salt) >>> 0;
    for (let i = 0; i < input.length; i++) {
      h ^= input.charCodeAt(i);
      h = Math.imul(h, 16777619) >>> 0;
    }
    return h.toString(16).toUpperCase().padStart(8, '0');
  };
  const h1 = hashPart(seed, 101);
  const h2 = hashPart(seed, 202);
  const h3 = hashPart(seed, 303);
  const h4 = hashPart(seed, 404);
  return `${h1}-${h2.slice(0, 4)}-4${h2.slice(5, 8)}-9${h3.slice(1, 4)}-${h3.slice(4, 8)}${h4}`;
}

